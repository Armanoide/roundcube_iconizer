<?php

declare(strict_types=1);

/**
 * Regenerate src/OfflineIcons.php from a locally extracted Tabler icon set.
 *
 * Usage: php bin/build-offline-list.php /path/to/tabler/icons
 * Keeps only names relevant to a mail sidebar so the offline payload stays small.
 */

$dir = $argv[1] ?? '';
if ($dir === '' || !is_dir($dir)) {
    fwrite(STDERR, "usage: php bin/build-offline-list.php <tabler-icons-dir>\n");
    exit(1);
}

$wanted = [
    'folder', 'folder-open', 'inbox', 'send', 'pencil', 'archive', 'trash',
    'alert-triangle', 'star', 'users', 'user', 'file-text', 'calendar',
    'briefcase', 'credit-card', 'receipt', 'home', 'book', 'camera', 'music',
    'photo', 'map-pin', 'shopping-cart', 'mail', 'bell', 'lock', 'shield',
    'cloud', 'database', 'settings',
];

$refs = [];
foreach ($wanted as $name) {
    if (is_file("{$dir}/{$name}.svg")) {
        $refs[] = "tabler:{$name}";
    } else {
        fwrite(STDERR, "missing: {$name}\n");
    }
}

$list = implode(",\n        ", array_map(fn ($r) => "'{$r}'", $refs));
$body = <<<'PHP'
<?php

declare(strict_types=1);

namespace Armanoide\Iconizer;

/**
 * Names of icons shipped in the bundled Tabler webfont fallback.
 * Generated by bin/build-offline-list.php — do not edit by hand.
 */
final class OfflineIcons
{
    /** @var list<string> */
    public const REFERENCES = [
        %LIST%,
    ];

    /** @return list<string> */
    public static function all(): array
    {
        return self::REFERENCES;
    }

    public static function has(string $reference): bool
    {
        return in_array($reference, self::REFERENCES, true);
    }
}
PHP;

file_put_contents(__DIR__ . '/../src/OfflineIcons.php', str_replace('%LIST%', $list, $body) . "\n");
echo 'wrote ' . count($refs) . " references\n";
